function commandQuestions(): InterviewQuestion[] {
  const out: InterviewQuestion[] = [];
  for (const cmd of commands) {
    if (!cmd.purpose || cmd.examples.length === 0) continue;
    const os: Track[] = cmd.posix ? ["Linux", "Unix", "POSIX"] : ["Linux"];
    const cat = "Commands";
    out.push(
      q({
        question: `What is the primary purpose of \`${cmd.name}\`?`,
        category: cat,
        difficulty: "Beginner",
        operatingSystem: os,
        tags: [cmd.name, cmd.category.toLowerCase()],
        type: "Conceptual",
        answer: cmd.purpose,
        explanation: cmd.summary,
        relatedTopics: ["bash-basics"],
        example: cmd.syntax,
      }),
    );
    out.push(
      q({
        question: `Give a practical example of using \`${cmd.name}\` and explain why it is used that way.`,
        category: cat,
        difficulty: "Beginner",
        operatingSystem: os,
        tags: [cmd.name, "example"],
        type: "Command",
        answer: `${cmd.examples[0].command} — ${cmd.examples[0].note}`,
        explanation: cmd.realWorld,
        relatedTopics: ["bash-basics"],
        example: cmd.examples[0].command,
      }),
    );
    if (cmd.flags[0]) {
      out.push(
        q({
          question: `In \`${cmd.name}\`, what does \`${cmd.flags[0].flag}\` do?`,
          category: cat,
          difficulty: "Beginner",
          operatingSystem: os,
          tags: [cmd.name, "flags"],
          type: "Command",
          answer: cmd.flags[0].meaning,
          explanation: `Flag list is not always portable. Check ${cmd.name}'s man page on the target OS.`,
          relatedTopics: ["help-systems"],
        }),
      );
    }
    if (cmd.flags[1]) {
      out.push(
        q({
          question: `When would you use \`${cmd.flags[1].flag}\` with \`${cmd.name}\`?`,
          category: cat,
          difficulty: "Intermediate",
          operatingSystem: os,
          tags: [cmd.name, "flags"],
          type: "How would you",
          answer: cmd.flags[1].meaning,
          explanation: cmd.examples[1]?.note || cmd.realWorld,
          relatedTopics: ["help-systems"],
        }),
      );
    }
    if (cmd.mistakes?.length) {
      out.push(
        q({
          question: `Name a common operational mistake with \`${cmd.name}\`.`,
          category: cat,
          difficulty: "Intermediate",
          operatingSystem: os,
          tags: [cmd.name, "mistakes"],
          type: "Why",
          answer: cmd.mistakes[0],
          explanation: cmd.warning || cmd.realWorld,
          relatedTopics: ["production-linux"],
        }),
      );
    }
    // cmd.interview[] holds question prompts with no authored answer, so they
    // are surfaced on the command page as "be ready for these" rather than
    // pushed into the bank paired with an unrelated answer.
    if (cmd.destructive) {
      out.push(
        q({
          question: `Why is \`${cmd.name}\` considered potentially destructive, and how do you use it safely?`,
          category: "Troubleshooting",
          difficulty: "Advanced",
          operatingSystem: os,
          tags: [cmd.name, "safety"],
          type: "Scenario",
          answer: cmd.warning || `Treat ${cmd.name} as irreversible without backups. Use explicit paths, dry-runs where available, and never interpolate untrusted variables.`,
          explanation: cmd.realWorld,
          relatedTopics: ["production-linux"],
        }),
      );
    }
  }
  return out;
}

/**
 * Questions derived from lesson content.
 *
 * Only lesson fields that are already written as a question/answer pair are
 * reused: the concept's own interview Q&A, its exercise, its worked output,
 * and its common mistake. Restating lesson prose as a pseudo-question
 * ("Explain in simple terms: X") inflates the count without adding anything
 * an interviewer would ask, so those variants are not generated.
 */
function topicQuestions(): InterviewQuestion[] {
  const out: InterviewQuestion[] = [];
  for (const t of topics) {
    for (const c of t.concepts) {
      out.push(
        q({
          question: c.interview.question,
          category: t.level >= 13 ? "Kernel" : t.level === 5 || t.level === 12 ? "Networking" : t.level === 3 || t.level === 10 ? "Security" : t.level === 4 ? "Processes" : t.level === 7 ? "Bash" : t.level === 14 ? "Unix" : "Linux Fundamentals",
          difficulty: t.difficulty === "Beginner" ? "Beginner" : t.difficulty === "Intermediate" ? "Intermediate" : "Advanced",
          operatingSystem: ["Linux"],
          tags: [t.slug, c.id],
          type: "Conceptual",
          answer: c.interview.answer,
          explanation: `${c.simple} ${c.technical}`,
          relatedTopics: [t.slug, ...c.related],
          example: c.example.command,
        }),
      );
      out.push(
        q({
          question: `You run \`${c.example.command}\`. What should you understand about the output?`,
          category: "Commands",
          difficulty: "Intermediate",
          operatingSystem: ["Linux"],
          tags: [t.slug, "output"],
          type: "Output",
          answer: c.example.explanation,
          explanation: `Sample output:\n${c.example.output}`,
          relatedTopics: [t.slug],
          example: c.example.output,
        }),
      );
      out.push(
        q({
          question: c.exercise.prompt,
          category: "Commands",
          difficulty: t.difficulty === "Beginner" ? "Beginner" : "Intermediate",
          operatingSystem: ["Linux"],
          tags: [t.slug, "exercise"],
          type: "How would you",
          answer: c.exercise.solution,
          explanation: c.simple,
          relatedTopics: [t.slug],
        }),
      );
      if (c.mistakes[0]) {
        out.push(
          q({
            question: `What mistake should you avoid regarding: ${c.title}?`,
            category: "Troubleshooting",
            difficulty: "Intermediate",
            operatingSystem: ["Linux"],
            tags: [t.slug, "mistakes"],
            type: "Why",
            answer: c.mistakes[0],
            explanation: c.practices[0] || c.technical,
            relatedTopics: [t.slug],
          }),
        );
      }
    }
  }
  return out;
}

